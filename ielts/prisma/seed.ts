import {
  PrismaClient,
  SkillType,
  ContentStatus,
  WritingTaskType,
  QuestionType,
} from "@prisma/client";

const prisma = new PrismaClient();

async function main() {
  console.log("Seeding database with IELTS writing prompts...");

  const writingMock = await prisma.mockExam.upsert({
    where: { id: "mock-writing-practice-1" },
    update: {},
    create: {
      id: "mock-writing-practice-1",
      title: "IELTS Academic Writing Practice Test 1",
      description: "Academic Writing imtihoni: Task 1 (Diagramma tahlili) va Task 2 (Insho).",
      status: ContentStatus.PUBLISHED,
      isDiagnostic: false,
      sections: {
        create: {
          id: "section-writing-1",
          skill: SkillType.WRITING,
          timeLimitMinutes: 60,
          orderIndex: 1,
          writingPrompts: {
            create: [
              {
                id: "prompt-task-1",
                taskType: WritingTaskType.TASK_1,
                title: "Electricity Generation by Energy Source",
                promptText:
                  "The chart below shows the percentage of electricity generated by different energy sources in New Zealand between 1990 and 2010.\n\nSummarise the information by selecting and reporting the main features, and make comparisons where relevant. Write at least 150 words.",
                status: ContentStatus.PUBLISHED,
                questions: {
                  create: {
                    skill: SkillType.WRITING,
                    questionType: QuestionType.ESSAY,
                    questionNumber: 1,
                    promptText: "Write your Task 1 response here.",
                    instruction: "Spend about 20 minutes on this task. Write at least 150 words.",
                    status: ContentStatus.PUBLISHED,
                  },
                },
              },
              {
                id: "prompt-task-2",
                taskType: WritingTaskType.TASK_2,
                title: "Impact of Remote Working",
                promptText:
                  "Some people believe that working from home brings many benefits to both employers and employees, while others think it leads to negative consequences for teamwork and productivity.\n\nDiscuss both views and give your own opinion. Give reasons for your answer and include any relevant examples from your own knowledge or experience. Write at least 250 words.",
                status: ContentStatus.PUBLISHED,
                questions: {
                  create: {
                    skill: SkillType.WRITING,
                    questionType: QuestionType.ESSAY,
                    questionNumber: 2,
                    promptText: "Write your Task 2 response here.",
                    instruction: "Spend about 40 minutes on this task. Write at least 250 words.",
                    status: ContentStatus.PUBLISHED,
                  },
                },
              },
            ],
          },
        },
      },
    },
  });

  console.log("Writing mock exam muvaffaqiyatli bazaga yuklandi:", writingMock.title);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });